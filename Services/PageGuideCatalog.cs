        /// <summary>取某页签的白话说明；没有配置返回 null（提示栏隐藏）。</summary>
        public static Guide? For(string key)
        {
            if (string.IsNullOrEmpty(key)) return null;
            return Map.TryGetValue(key, out var g) ? g : null;
        }

        /// <summary>所有已配置的页签（守卫用它检查「有没有漏了哪一页」）。</summary>
        public static IReadOnlyCollection<string> Keys => Map.Keys;
