using System.ComponentModel;
using System.Runtime.CompilerServices;

namespace NoCodeMotion.Models
{
    /// <summary>料盘中的一个单元格（二维阵列中的一格）。</summary>
    public class TrayCell : INotifyPropertyChanged
    {
        private int _row;
        private int _col;
        private bool _occupied;   // 是否有料

        public int Row { get => _row; set => SetField(ref _row, value); }
        public int Col { get => _col; set => SetField(ref _col, value); }
        public bool Occupied { get => _occupied; set => SetField(ref _occupied, value); }

        public event PropertyChangedEventHandler? PropertyChanged;

        protected void OnPropertyChanged([CallerMemberName] string? propertyName = null)
            => PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(propertyName));

        protected bool SetField<T>(ref T field, T value, [CallerMemberName] string? propertyName = null)
        {
            if (Equals(field, value)) return false;
            field = value;
            OnPropertyChanged(propertyName);
            return true;
        }
    }
}
