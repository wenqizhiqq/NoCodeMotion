            // 同时清掉空行（避免出现连续空段破坏阅读节奏）。
            InitLines();
            DataContext = this;
        }

        private void InitLines()
        {
            for (int i = 1; i <= 15; i++)
            {
                var body = (string)GetType().GetProperty("S" + i + "_Body")!.GetValue(this)!;
                var lines = body.Split('\n')
                                .Select(s => s.TrimEnd())
                                .Where(s => !string.IsNullOrWhiteSpace(s))
                                .ToList();
                GetType().GetProperty("S" + i + "_Lines")!.SetValue(this, lines);
            }
        }

