        public List<string> Roles { get; } = new() { "操作员", "工程师", "维护", "管理员" };

        private string _currentRole = "操作员";
        public string CurrentRole
        {
            get => _currentRole;
            set
            {
                if (_currentRole == value) return;
                _currentRole = value;
                BuildSections();
                OnPC(nameof(CurrentRole));
                OnPC(nameof(HeaderText));
            }
        }

        /// <summary>顶部标题（随角色变化）。</summary>
        public string HeaderText => $"{CurrentRole}使用说明书";

        private List<ManualSection> _sections = new();
        public List<ManualSection> Sections
        {
            get => _sections;
            set { _sections = value; OnPC(nameof(Sections)); }
        }

        public OperatorManualPage()
        {
            InitializeComponent();
            BuildSections();
            DataContext = this;
        }

        /// <summary>根据当前角色构建章节列表（每行按 \n 切分并去掉空行）。</summary>
        private void BuildSections()
        {
            var raw = CurrentRole switch
            {
                "工程师" => EngineerSections(),
                "维护" => MaintenanceSections(),
                "管理员" => AdminSections(),
                _ => OperatorSections()
            };
            var list = new List<ManualSection>();
            foreach (var (title, body) in raw)
            {
                var lines = body.Split('\n')
                                .Select(s => s.TrimEnd())
                                .Where(s => !string.IsNullOrWhiteSpace(s))
                                .ToList();
                list.Add(new ManualSection { Title = title, Lines = lines });
            }
            Sections = list;
        }

