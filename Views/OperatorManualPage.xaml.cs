        public List<ManualSection> Sections
        {
            get => _sections;
            set { _sections = value; OnPC(nameof(Sections)); }
        }

        public OperatorManualPage()
        {
            InitializeComponent();
            BuildSections();
            DataContext = this;
        }

        /// <summary>根据当前角色构建章节列表（每行按 \n 切分并去掉空行）。</summary>
        private void BuildSections()
        {
            var raw = CurrentRole switch
            {
                "工程师" => EngineerSections(),
                "维护" => MaintenanceSections(),
                "管理员" => AdminSections(),
                "关于" => AboutSections(),
                "新手入门" => BeginnerSections(),
                _ => OperatorSections()
            };
            var list = new List<ManualSection>();
            foreach (var (title, body) in raw)
            {
                var lines = body.Split('\n')
                                .Select(s => s.TrimEnd())
                                .Where(s => !string.IsNullOrWhiteSpace(s))
                                .ToList();
                list.Add(new ManualSection { Title = title, Lines = lines });
            }
            Sections = list;
        }

