        public List<string> Roles { get; } = new() { "新手入门", "操作员", "工程师", "维护", "管理员", "关于" };

        private string _currentRole = "操作员";
        public string CurrentRole
        {
            get => _currentRole;
            set
            {
                if (_currentRole == value) return;
                _currentRole = value;
                BuildSections();
                OnPC(nameof(CurrentRole));
                OnPC(nameof(HeaderText));
            }
        }

        /// <summary>顶部标题（随角色变化；「关于」页不用"使用说明书"后缀）。</summary>
        public string HeaderText => CurrentRole == "关于" ? "关于本软件" : $"{CurrentRole}使用说明书";

